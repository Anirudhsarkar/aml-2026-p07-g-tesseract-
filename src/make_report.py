"""Assemble a DRAFT report (report/report.md) from the files in results/.

Every number comes from the result files; the interpretation sentences are
data-driven templates. The team must read, edit and own the final text, and
export it to PDF (4-6 pages) before submission.
"""
import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"
FIG = "../results/figures"
MISSING = "_(not available: run the earlier pipeline steps)_"


def read_csv(name):
    path = RES / name
    return pd.read_csv(path) if path.exists() else None


def read_json(name):
    path = RES / name
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def table(df, floatfmt="{:,.3f}"):
    if df is None:
        return MISSING
    out = df.copy()
    for col in out.columns:
        if pd.api.types.is_float_dtype(out[col]):
            out[col] = out[col].map(lambda v: "" if pd.isna(v) else floatfmt.format(v))
    header = "| " + " | ".join(map(str, out.columns)) + " |"
    sep = "|" + "|".join(["---"] * len(out.columns)) + "|"
    body = ["| " + " | ".join(map(str, row)) + " |" for row in out.itertuples(index=False)]
    return "\n".join([header, sep, *body])


def figure(name, caption):
    return f"![{caption}]({FIG}/{name})\n*{caption}*" if (RES / "figures" / name).exists() else ""


def main():
    funnel = read_csv("cleaning_funnel.csv")
    cleaning = read_json("cleaning_summary.json") or {}
    eda = read_json("eda_summary.json") or {}
    rfm = read_json("rfm_summary.json") or {}
    km = read_csv("kmeans_metrics.csv")
    comp = read_json("clustering_comparison.json") or {}
    stability = read_csv("kmeans_stability.csv")
    hier = read_csv("hierarchical_metrics.csv")
    seg = read_json("segment_summary.json") or {}
    profiles = read_csv("segment_profiles.csv")
    kselect = read_csv("k_selection.csv")
    metrics = read_csv("metrics.csv")
    cls = read_json("classification_summary.json") or {}
    patterns = eda.get("purchasing_patterns", {})

    lines = []
    w = lines.append
    w("# P07 - Customer Segmentation for an Online Retailer")
    w("**Applied Machine Learning (CSAI2017P) - Team Tesseract**\n")
    w("> **DRAFT generated by `src/make_report.py` from `results/`.** Read it, correct the "
      "interpretation, and shorten or extend it to 4-6 pages before submission.\n")

    w("## 1. Question and approach")
    w("Which distinct customer groups exist in online retail transactions, and can a model assign a "
      "new customer to a segment using only early purchase behaviour? We clean the UCI Online Retail II "
      "data, build Recency-Frequency-Monetary (RFM) features per customer, compare K-Means, hierarchical "
      "clustering and DBSCAN, interpret the segments, and predict segments from a customer's first weeks "
      "of activity without leakage.\n")

    w("## 2. Data and cleaning")
    if eda:
        w(f"After cleaning, {eda.get('cleaned_rows', 0):,} transactions remain from "
          f"{eda.get('unique_customers', 0):,} customers, {eda.get('unique_invoices', 0):,} invoices and "
          f"{eda.get('countries', 0)} countries "
          f"({str(eda.get('date_min', ''))[:10]} to {str(eda.get('date_max', ''))[:10]}).")
    if cleaning.get("cleaning_retention_percent"):
        w(f"Retention of the raw rows is {cleaning['cleaning_retention_percent']:.2f}%.")
    w("\n" + table(funnel, "{:,.0f}") + "\n")
    w("Cancellation invoices (Invoice starting with `C`) are excluded rather than netted against the original "
      "purchases, so Monetary is gross retained sales; this is a stated limitation.\n")

    w("## 3. Exploratory analysis")
    if eda:
        peak, low = eda.get("monthly_revenue_peak", {}), eda.get("monthly_revenue_low", {})
        top = eda.get("top_product_by_revenue", {})
        country = eda.get("top_country_by_revenue", {})
        w(f"Gross revenue is GBP {eda.get('total_gross_revenue_gbp', 0):,.0f}. Among complete months the peak "
          f"is {peak.get('Month')} (GBP {peak.get('revenue_gbp', 0):,.0f}) and the low is {low.get('Month')} "
          f"(GBP {low.get('revenue_gbp', 0):,.0f}); partial months ({', '.join(eda.get('partial_months', [])) or 'none'}) "
          f"are excluded from these statements. The top product by revenue is {top.get('Description')} "
          f"(GBP {top.get('revenue_gbp', 0):,.0f}) and the top country is {country.get('Country')} "
          f"(GBP {country.get('revenue_gbp', 0):,.0f}).")
    if patterns:
        w(f"\n**Purchasing patterns.** {patterns['one_time_share']:.1%} of customers bought only once; "
          f"customers placed a median of {patterns['median_invoices_per_customer']:.0f} invoice(s), with a median "
          f"average invoice value of GBP {patterns['median_avg_invoice_value_gbp']:,.0f}. The top 10% of customers "
          f"account for {patterns['top_10_percent_customers_revenue_share']:.1%} of revenue. Busiest weekday by "
          f"revenue: {patterns['busiest_weekday_by_revenue']}; busiest hour: {patterns['busiest_hour_by_revenue']}:00.")
    w("\n" + figure("monthly_revenue.png", "Monthly revenue (partial months marked)"))
    w(figure("invoices_per_customer.png", "Invoices per customer"))
    w("")

    w("## 4. RFM features")
    stats = rfm.get("raw_feature_statistics", {})
    skew_log = rfm.get("log_feature_skewness", {})
    if stats:
        df = pd.DataFrame([{"feature": f, "mean": s["mean"], "median": s["median"], "max": s["max"],
                            "skew_raw": s["skewness"], "skew_log1p": skew_log.get(f)} for f, s in stats.items()])
        w(f"Recency is days from {rfm.get('reference_date')} to the last purchase; Frequency is distinct invoices; "
          "Monetary is GBP spent. Raw Frequency and Monetary are strongly right-skewed, so we apply `log1p` and "
          "standardise before clustering.\n")
        w(table(df) + "\n")
    else:
        w(MISSING)

    w("## 5. Clustering")
    if km is not None:
        cols = [c for c in ["k", "inertia", "silhouette_full", "davies_bouldin", "calinski_harabasz",
                            "min_cluster_share"] if c in km.columns]
        w("**K-Means, k = 2-10**\n")
        w(table(km[cols]) + "\n")
        w(figure("kmeans_elbow_curve.png", "K-Means elbow curve"))
    if stability is not None:
        w("\n**Stability (ARI across 20 subsamples of 80%)**\n")
        w(table(stability[["k", "stability_ari_mean", "stability_ari_std"]]) + "\n")
    if hier is not None:
        best = hier.loc[hier.groupby("linkage")["silhouette"].idxmax(), ["linkage", "k", "silhouette", "cophenetic_correlation"]]
        w("**Hierarchical clustering: best silhouette per linkage**\n")
        w(table(best) + "\n")
        w(figure("dendrogram_ward.png", "Ward dendrogram (truncated)"))
    db = comp.get("dbscan", {})
    if db:
        w(f"\n**DBSCAN.** {db.get('finding')}")
        ref = db.get("reference_configuration_for_noise_analysis", {})
        if ref:
            w(f"Noise analysis used eps={ref.get('eps'):.2f}, min_samples={ref.get('min_samples')} "
              f"({ref.get('noise_percent', 0):.1f}% noise, {ref.get('clusters')} clusters).")
    w("")

    w("## 6. Segments and recommendations")
    if seg:
        w(f"Final choice: K-Means with k = {seg['final_k']} ({seg['selection_rule']}).\n")
    if kselect is not None:
        w(table(kselect[["k", "silhouette_full", "min_cluster_share", "stability_ari_mean", "meets_constraints", "chosen"]]) + "\n")
    if profiles is not None:
        view = profiles[["SegmentName", "customers", "customer_share", "revenue_share",
                         "recency_median", "frequency_median", "monetary_median"]]
        w(table(view) + "\n")
        w(figure("segments_pca.png", "Segments in PCA space"))
        w(figure("segment_share_vs_revenue.png", "Customer share vs revenue share"))
        w("\n**Recommended actions**\n")
        for row in profiles.itertuples():
            w(f"- **{row.SegmentName}** ({row.description}) - {row.recommended_actions}")
    w("")

    w("## 7. Predicting segments from early behaviour")
    audit = cls.get("audit", {})
    if audit:
        w(f"Features use only each customer's first {audit['window_days']} days after their first purchase "
          f"and a {audit['horizon_days']}-day future horizon for the labels ({audit['eligible_customers']:,} customers with both "
          "windows complete). Lifetime RFM and acquisition date are "
          "excluded; scaling is fitted inside pipelines on the training split only. Two label sources are reported: "
          "**future** (segments built only from activity in the horizon after the early window; the leakage-free headline) and "
          "**lifetime** (the Phase 5 segments; optimistic because the labels include the early window).\n")
    if metrics is not None:
        main_rows = metrics[(metrics.split == "test") & metrics.metric.isin(["accuracy", "macro_f1", "balanced_accuracy"])]
        pivot = main_rows.pivot_table(index=["task", "model"], columns="metric", values="value").reset_index()
        w(table(pivot) + "\n")
        for task, info in cls.get("tasks", {}).items():
            w(f"- `{task}`: {info['customers']:,} customers; best model by cross-validated macro-F1: "
              f"**{info['best_model_by_cv_macro_f1']}**.")
        w("")
        for task in cls.get("tasks", {}):
            w(figure(f"confusion_matrix_{task}.png", f"Confusion matrix ({task})"))
        recalls = metrics[(metrics.split == "test") & metrics.metric.str.startswith("recall[")]
        if len(recalls):
            w("\n**Per-class recall (test)**\n")
            w(table(recalls[["task", "model", "metric", "value"]]) + "\n")
    w("")

    w("## 8. Limitations")
    for item in [
        "Cancellations are excluded, not netted, so Monetary is gross sales and a few reversed orders may inflate individual customers.",
        "Segment names are heuristic labels from centroid thresholds; the clusters are not ground truth.",
        "Customers acquired in the last window+horizon days are excluded from the classification task, so very recent customers are not represented.",
        "A single train/test split on one dataset (UK retailer, 2009-2011) limits how far the results generalise.",
        "Silhouette scores on RFM data are modest because customer behaviour is continuous rather than sharply clustered.",
    ]:
        w(f"- {item}")
    w("\n## 9. Reproducibility")
    w("See `REPRODUCIBILITY.md`. Run `python src/run_all.py` from the repository root after placing "
      "`data/raw/online_retail_II.xlsx`. All seeds are fixed (`random_state=42`).\n")
    w("## 10. AI and external resources")
    w("Claude (Anthropic) was used to help write and test the Phase 2 and Phase 4-7 scripts. All code was "
      "reviewed and must be understood by each member. Data: UCI Online Retail II. Libraries: pandas, NumPy, "
      "scikit-learn, SciPy, Matplotlib.")

    out = ROOT / "report" / "report.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
